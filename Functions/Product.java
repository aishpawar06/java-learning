//Find the product of 2 numbers using function 
package Functions;

public class Product {
    public static int multiply(int a, int b){
        return a*b;
    }
    public static void main(String args[]){
        int a=5;
        int b=10;
        System.out.println(a + " x "+ b + " = " + multiply(a,b));

    } 
}
